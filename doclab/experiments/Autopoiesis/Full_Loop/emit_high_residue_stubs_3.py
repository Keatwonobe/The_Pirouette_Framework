#!/usr/bin/env python3
"""
emit_high_residue_stubs_v7.py

v7-aware stub emitter for the Pirouette autopoietic loop.

Differences from the v6-ish emitter:
- emits v7-style headers (resonance, autopoiesis, origin)
- passes shepherd context through
- supports novelty_penalty so we don't keep hitting the same tile
- can run multiple cycles with a quota
- ready to hand off to context-builder + author

Requires:
  from DDE_Pirouette import IdeaManifoldSurveyor
  ...with find_voids(...) supporting shepherd_context + novelty_penalty
"""

import argparse
from pathlib import Path
from datetime import datetime
import time

from DDE_Pirouette import IdeaManifoldSurveyor  # integrated in your project


V7_TEMPLATE = """---
id: {id}
title: {title}
version: 7.0
layer: manifold
status: draft
origin:
  atlas_tile: [{x}, {y}]
  atlas_gen: {atlas_gen}
  emitted_by: dde-pirouette
  shepherd_context: {shepherd_context}
  parents: {parents}
resonance:
  dark_residue: {dark_residue}
  target_residue: {target_residue}
  delta_gamma: {delta_gamma}
  continuity_tol: 0.05
autopoiesis:
  cycle: {cycle}
  acceptance: pending
  quota_run: {quota_run}
context_sources:
  - dde_glob_manifest_modules_outbox.json
  - pirouette_dict.dictpack
  - essentialized_pirouette.md
task:
  intent: "bridge local manifold gap at ({x},{y}) toward shepherd '{shepherd_context}'"
  audience: "api-synthesis"
  output_min: 400
---
## Purpose
Autogenerated v7 bridge emitted by DDE-Pirouette to reduce local dark residue,
raise usable Ki, and tie the tile to the current shepherd context.

## Context
This atlas location showed high dark residue or low neighbor density.
Existing module here: {existing}
Shepherd requested alignment toward: {shepherd_context}

## Task
Describe the missing connective tissue between this tile, its neighbors,
and the shepherd context "{shepherd_context}".
Specify:
- Γ/Ki deltas that move {dark_residue} → {target_residue}
- temporal adherence (Tₐ) appropriate for this domain
- closure style (core/dome/bridge)
- validation / falsifiability steps
- how this bridge advances the shepherd context
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atlas", required=True,
                    help="path to dde_glob_manifest_modules_outbox.json")
    ap.add_argument("--outdir", default="autopoiesis_runs/stubs",
                    help="directory to write v7 stubs into")
    ap.add_argument("--shepherd", default="pirouette-general",
                    help="context label to point bridges at")
    ap.add_argument("--top", type=int, default=10,
                    help="how many tiles per cycle")
    ap.add_argument("--cycles", type=int, default=1,
                    help="how many emission cycles to run")
    ap.add_argument("--novelty-penalty", type=float, default=0.25,
                    help="penalize already-emitted tiles so we go deeper each cycle")
    ap.add_argument("--sleep", type=float, default=0.0,
                    help="optional delay between cycles")
    ap.add_argument("--target-residue", type=float, default=0.30,
                    help="where we want the tile to end up")
    args = ap.parse_args()

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    surveyor = IdeaManifoldSurveyor(
        atlas_json_path=args.atlas,
        neighbor_radius=1,
    )

    print(f"[v7-emitter] loaded {len(surveyor.locations)} atlas locations from {args.atlas}")

    # allow the surveyor to remember tiles we already emitted for
    if not hasattr(surveyor, "emitted_tiles"):
        surveyor.emitted_tiles = set()

    quota_run = datetime.now().strftime("%Y%m%dT%H%M%S")

    for cycle in range(1, args.cycles + 1):
        voids = surveyor.find_voids(
            min_neighbors=2,
            shepherd_context=args.shepherd,
            context_weight=0.4,
            novelty_penalty=args.novelty_penalty,
        )
        if not voids:
            print(f"[v7-emitter] no voids found in cycle {cycle}, stopping.")
            break

        top_voids = voids[: args.top]
        surveyor.mark_emitted([(x, y) for (x, y, _) in top_voids])

        for rank, (x, y, score) in enumerate(top_voids, start=1):
            existing_id = None
            for mid, loc in surveyor.locations.items():
                if loc["x"] == x and loc["y"] == y:
                    existing_id = mid
                    break

            if existing_id:
                stub_id = f"{existing_id}_AUTH-BRIDGE"
                parents = [existing_id]
            else:
                stub_id = f"AUTH-VOID-{x:02d}-{y:02d}"
                parents = []

            # we don't actually know the exact residue at this tile here,
            # but many of your v7s used 0.47 → 0.30, so we'll keep that default
            dark_residue = 0.47
            delta_gamma = args.target_residue - dark_residue  # typically negative

            stub_text = V7_TEMPLATE.format(
                id=stub_id,
                title=f"v7 Manifold Bridge at ({x},{y})",
                x=x,
                y=y,
                atlas_gen=cycle,
                shepherd_context=args.shepherd,
                parents=parents,
                dark_residue=dark_residue,
                target_residue=args.target_residue,
                delta_gamma=delta_gamma,
                existing=existing_id or "∅",
                cycle=cycle,
                quota_run=quota_run,
            )

            out_path = outdir / f"{stub_id}.md"
            out_path.write_text(stub_text, encoding="utf-8")
            print(f"[v7-emitter] cycle={cycle} wrote {out_path} (score={score:.3f})")

        if args.sleep > 0 and cycle < args.cycles:
            time.sleep(args.sleep)


if __name__ == "__main__":
    main()
