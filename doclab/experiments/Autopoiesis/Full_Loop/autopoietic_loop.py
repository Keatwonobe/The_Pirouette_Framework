#!/usr/bin/env python3
"""
Autopoietic Pirouette Loop
- emit stubs from DDE atlas (paw-signal)
- author them (external API / LLM)
- ratify them (local)
- sort accepted vs discarded
- stop when:
    a) quota is reached
    b) debate rejection >= 50%
"""

import argparse
from pathlib import Path
from datetime import datetime

from DDE_Pirouette import IdeaManifoldSurveyor  # your integrated surveyor

# try to pull in your real ratifier, fall back to the simple one
try:
    from ratify import synthesize_and_ratify, sanitize_and_save_ratified_module
    HAVE_RATIFIER = True
except ImportError:
    HAVE_RATIFIER = False


def call_author_api(stub_text: str) -> str:
    # placeholder — this is where your API call goes
    return stub_text + "\n\n## Generated\nThis section was filled by the authoring API.\n"


def simple_local_ratify(module_text: str) -> tuple[bool, str]:
    txt = module_text.strip()
    accepted = True
    if not txt.startswith("---"):
        accepted = False
    if "## Purpose" not in txt and "## Law" not in txt:
        accepted = False
    return accepted, txt


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--atlas", required=True,
                   help="dde_glob_manifest_modules_outbox.json")
    p.add_argument("--outdir", default="./autopoiesis_runs",
                   help="where to store accepted/discarded modules")
    p.add_argument("--quota", type=int, default=25,
                   help="max modules to try this run")
    p.add_argument("--batch", type=int, default=25,
                   help="how many stubs to emit per cycle")
    p.add_argument("--shepherd", default="altruism",
                   help="context to steer stubs toward")
    args = p.parse_args()

    outdir = Path(args.outdir)
    accepted_dir = outdir / "accepted"
    discarded_dir = outdir / "discarded"
    stubs_dir = outdir / "stubs"
    for d in (accepted_dir, discarded_dir, stubs_dir):
        d.mkdir(parents=True, exist_ok=True)

    surveyor = IdeaManifoldSurveyor(args.atlas)

    total_attempted = 0
    total_rejected = 0
    cycle = 0

    while total_attempted < args.quota:
        cycle += 1
        voids = surveyor.find_voids(
            min_neighbors=5,
            shepherd_context=args.shepherd,
            context_weight=0.4,
            novelty_penalty=0.3,
        )
        voids = voids[: args.batch]

        if not voids:
            print("No more voids detected, stopping.")
            break

        surveyor.mark_emitted([(x, y) for (x, y, _) in voids])

        for (x, y, score) in voids:
            if total_attempted >= args.quota:
                break

            # locate existing module at this tile
            existing_id = None
            for mid, loc in surveyor.locations.items():
                if loc["x"] == x and loc["y"] == y:
                    existing_id = mid
                    break

            if existing_id:
                stub_id = f"{existing_id}_AUTH-BRIDGE"
                parents = [existing_id]
            else:
                stub_id = f"AUTH-VOID-{x:02d}-{y:02d}"
                parents = []

            created_at = datetime.now().isoformat()
            stub_txt = f"""---
id: {stub_id}
title: Idea Manifold Bridge near ({x},{y})
version: 0.1-dde
domain: DOMA
layer: manifold        # manifold | translator | shepherd
status: draft          # draft | ratified | quarantined
origin:
  atlas_tile: [{x},{y}]
  atlas_score: {score:.4f}
  atlas_gen:          # which autopoietic pass made it
  emitted_by: dde-pirouette
  shepherd_context: {args.shepherd}
  parents: {parents}
  detected_gap: low_neighbor_density
resonance:
  dark_residue: 0.47   # as measured at emit time
  target_residue: 0.30 # what this module is trying to get us to
  closure_style: bridge  # core | dome | bridge | lattice
  temporal_adherence: medium
  gamma_profile: medium
context_sources:
  dictpack_keys: ["pirouette", "closure", "lagrangian"]
  essentialized_refs: []
autopoiesis:
  emitted_at: {created_at}
  debate_round: 
  acceptance: pending   # accepted | rejected | pending
  quota_run: 
task:
  intent: "close conceptual void between CORE-006 and closure kits for public-facing AI synthesis"
  audience: "api-synthesis"
  output_min: 400
---
## Purpose
Autogenerated bridge emitted by DDE-Pirouette manifold survey.

## Context
Tile ({x},{y}) scored high in dark residue / low neighbor density.
Shepherd context: {args.shepherd}

## Task
Connect this tile to its neighbors AND to the shepherd context.
"""

            # write stub
            (stubs_dir / f"{stub_id}.md").write_text(stub_txt, encoding="utf-8")

            # AUTHOR
            authored = call_author_api(stub_txt)

            # RATIFY
            if HAVE_RATIFIER:
                # if you want to actually save via your ratifier, do it here
                accepted, cleaned = True, authored
            else:
                accepted, cleaned = simple_local_ratify(authored)

            total_attempted += 1
            if not accepted:
                total_rejected += 1
                (discarded_dir / f"{stub_id}.md").write_text(cleaned, encoding="utf-8")
                print(f"[{cycle}] ❌ Rejected {stub_id} (score={score:.3f})")
            else:
                (accepted_dir / f"{stub_id}.md").write_text(cleaned, encoding="utf-8")
                print(f"[{cycle}] ✅ Accepted {stub_id} (score={score:.3f})")

            # early stop on bad debate ratio
            if total_attempted >= 5:
                rejection_ratio = total_rejected / total_attempted
                if rejection_ratio >= 0.5:
                    print(f"Stopping: rejection ratio {rejection_ratio:.2f} ≥ 0.5")
                    print(f"Attempted={total_attempted}, Rejected={total_rejected}")
                    return

    print("Done.")
    print(f"Attempted={total_attempted}, Rejected={total_rejected}")


if __name__ == "__main__":
    main()
