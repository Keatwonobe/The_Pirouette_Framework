#!/usr/bin/env python3
"""
Pirouette v7 Author (The "Modernized Weaver")

This script is the core authoring engine of the autopoietic loop.
It is designed to be called by an orchestrator (like 'autopoietic_loop_v7.py').

It takes two primary inputs:
1.  A "STUB" file (generated by 'emit_high_residue_stubs_2.py')
2.  A "CONTEXT" file (generated by 'build_context.py')

It expands the simple STUB into a full, canonical Pirouette v7 module
by following a rigorous, math-centric, and falsifiable structure.
"""

import google.generativeai as genai
import os
import argparse
from pathlib import Path
from datetime import datetime
import re
import time

# --- Configuration ---
API_KEY = os.getenv('GOOGLE_API_KEY')
if not API_KEY:
    raise ValueError("Error: GOOGLE_API_KEY environment variable not set.")
genai.configure(api_key=API_KEY)

# --- The Canonical v7 Module Constitution ---
# This is the "master prompt" that defines the v7 module structure.
INSTRUCTIONS = """
Your task is to act as the Pirouette Framework's core authoring intelligence.
You will expand a given STUB file into a full, canonical Pirouette v7 module.
You will be provided with the STUB and a CONTEXT blob containing essentialized definitions and dictionary terms.

You MUST generate a single, complete, valid markdown file.
You MUST NOT include any commentary outside the markdown file.
The file MUST follow this exact structure:

---
(Full YAML Header from STUB)
---

## Law
This is the axiomatic, mathematical core of the module.
- It MUST be math-centric and use formal, dense, academic language.
- It MUST integrate with the Pirouette Lagrangian (𝓛_p) and its core components (Γ, Ki, Tₐ), referencing them explicitly.
- It MUST directly address and solve the 'Task' specified in the STUB.
- If the STUB is a bridge module, the Law section must define the 'Γ/Ki deltas' mathematically.

## Philosophy
This section translates the 'Law' into its philosophical implications.
- What does this concept mean for ontology, existence, or consciousness?
- Use the abstract, poetic, and philosophical voice of the Pirouette framework.
- It should answer: "What is the 'so what' of the Law?"

## Falsifiability Matrix
This is a required section.
- Provide at least two (2) specific, testable, quantitative criteria that would falsify the claims made in the '## Law' section.
- This MUST be a structured list or a markdown table.
- Example: "Observation of a system where Γ > 0 but no Ki resonance is formed."
- Example: "Measurement of the electron's anomalous magnetic moment diverging from α/2π."

## Assemblé
This is the final, poetic, required section.
- End the module with a single, short, poetic statement that encapsulates the module's core idea.
- Example: "The void, answering its own echo."
- Example: "A line drawn in thought, now held fast in the light."
"""

def get_model(model_name="gemini-2.5-flash-preview-09-2025"):
    """Initializes and returns the generative model."""
    return genai.GenerativeModel(model_name)

def read_file(file_path: Path) -> str:
    """Reads the content of a file."""
    try:
        return file_path.read_text(encoding='utf-8')
    except Exception as e:
        print(f"Error reading {file_path.name}: {e}")
        return ""

def generate_module(stub_content: str, context_content: str) -> str:
    """Generates the full module content using the Gemini API."""
    model = get_model()

    # Combine all inputs into the final prompt for the model
    prompt = f"""
{INSTRUCTIONS}

---
## STUB
{stub_content}
---

---
## CONTEXT
{context_content}
---
"""

    print(f"[author_v7] Calling Gemini API to expand stub...")
    try:
        # Exponential backoff for API calls
        max_retries = 5
        delay = 2
        for i in range(max_retries):
            try:
                response = model.generate_content(prompt)
                if hasattr(response, 'text'):
                    return response.text.strip()
                else:
                    print(f"[author_v7] API response had no 'text' attribute. Feedback: {response.prompt_feedback}")
                    return f"ERROR: Malformed API response. {response.prompt_feedback}"
            except Exception as e:
                if "Resource has been exhausted" in str(e) or "503" in str(e) or "service is currently unavailable" in str(e):
                    print(f"[author_v7] API busy. Retrying in {delay}s... ({i+1}/{max_retries})")
                    time.sleep(delay)
                    delay *= 2
                else:
                    raise e # Re-raise other errors
        
        return f"ERROR: API failed after {max_retries} retries."

    except Exception as e:
        print(f"[author_v7] CRITICAL ERROR calling Gemini API: {e}")
        return f"ERROR: API call failed. {e}"

def main():
    parser = argparse.ArgumentParser(description="Pirouette v7 Authoring Engine")
    parser.add_argument("--stub", required=True, help="Path to the STUB .md file (from emit_high_residue_stubs_2.py)")
    parser.add_argument("--context", required=True, help="Path to the CONTEXT .txt file (from build_context.py)")
    parser.add_argument("--out", required=True, help="Path to save the new, fully-authored .md module")
    args = parser.parse_args()

    stub_path = Path(args.stub)
    context_path = Path(args.context)
    out_path = Path(args.out)

    if not stub_path.exists():
        print(f"[author_v7] Error: Stub file not found at {stub_path}")
        return
    if not context_path.exists():
        print(f"[author_v7] Error: Context file not found at {context_path}")
        return

    print(f"[author_v7] Loading stub: {stub_path.name}")
    stub_content = read_file(stub_path)
    
    print(f"[author_v7] Loading context: {context_path.name}")
    context_content = read_file(context_path)

    if not stub_content or not context_content:
        print("[author_v7] Error: Stub or context content is empty. Aborting.")
        return

    # Generate the full module
    new_module_content = generate_module(stub_content, context_content)

    # Save the output
    try:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(new_module_content, encoding='utf-8')
        print(f"[author_v7] Successfully authored and saved module to: {out_path}")
    except Exception as e:
        print(f"[author_v7] Error saving module to {out_path}: {e}")

if __name__ == "__main__":
    main()