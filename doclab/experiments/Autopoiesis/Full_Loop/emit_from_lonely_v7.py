#!/usr/bin/env python3
"""
emit_from_lonely_v7.py

Emit v7 stubs from either:
- the atlas (fallback / classic), or
- a loneliness list (lonely_rank.json) that was just produced

This lets us keep the loop hot without re-DDE'ing the whole framework.
"""

import argparse
import json
from pathlib import Path
from datetime import datetime

V7_TEMPLATE = """---
id: {id}
title: {title}
version: 7.0
layer: manifold
status: draft
origin:
  atlas_tile: [{x}, {y}]
  atlas_gen: {atlas_gen}
  emitted_by: dde-pirouette
  shepherd_context: {shepherd_context}
  parents: {parents}
resonance:
  dark_residue: {dark_residue}
  target_residue: {target_residue}
  delta_gamma: {delta_gamma}
  continuity_tol: 0.05
autopoiesis:
  cycle: {cycle}
  acceptance: pending
  quota_run: {quota_run}
context_sources:
  - dde_glob_manifest_modules_outbox.json
  - pirouette_dict.dictpack
  - essentialized_pirouette.md
task:
  intent: "bridge local manifold gap toward shepherd '{shepherd_context}'"
  audience: "api-synthesis"
  output_min: 400
---
## Purpose
Autogenerated v7 bridge emitted from loneliness list to reduce dark residue,
raise usable Ki, and tie the node to the shepherd context.

## Context
This item was ranked as lonely or underlinked in the current corpus.
Shepherd requested alignment toward: {shepherd_context}

## Task
Describe the missing connective tissue between this item, its implicit neighbors,
and the shepherd context "{shepherd_context}". Specify Γ/Ki deltas toward
{target_residue}, temporal adherence, and falsifiability steps.
"""

def load_lonely(path: Path):
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))

def load_authored_ids(authored_dir: Path):
    ids = set()
    if authored_dir.exists():
        for p in authored_dir.glob("*.md"):
            ids.add(p.stem)
    return ids

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lonely", default="lonely_rank.json",
                    help="module loneliness list to emit from")
    ap.add_argument("--outdir", default="autopoiesis_runs/stubs",
                    help="where to write stubs")
    ap.add_argument("--shepherd", default="altruism",
                    help="shepherd / goal phrase")
    ap.add_argument("--authored", default="autopoiesis_runs/authored",
                    help="folder of already authored modules to avoid dupes")
    ap.add_argument("--top", type=int, default=10,
                    help="how many lonely items to turn into stubs")
    ap.add_argument("--target-residue", type=float, default=0.30)
    args = ap.parse_args()

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    lonely = load_lonely(Path(args.lonely))
    authored_ids = load_authored_ids(Path(args.authored))
    quota_run = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")

    emitted = 0
    atlas_gen = 0  # unknown here, so 0 / meta
    cycle = 0

    for item in lonely:
        mid = item["id"]
        path = item.get("path", "")
        # skip if we already authored something with this name
        if mid in authored_ids:
            continue

        # we may not have atlas coords in lonely list, so default
        x = item.get("x", 0)
        y = item.get("y", 0)

        # parent can be the id itself, so the author knows what to expand
        parents = [mid]

        dark_residue = 0.47
        delta_gamma = args.target_residue - dark_residue

        stub_text = V7_TEMPLATE.format(
            id=f"{mid}_AUTH-BRIDGE",
            title=f"v7 Bridge for {mid}",
            x=x,
            y=y,
            atlas_gen=atlas_gen,
            shepherd_context=args.shepherd,
            parents=parents,
            dark_residue=dark_residue,
            target_residue=args.target_residue,
            delta_gamma=delta_gamma,
            cycle=cycle,
            quota_run=quota_run,
        )

        out_path = outdir / f"{mid}_AUTH-BRIDGE.md"
        out_path.write_text(stub_text, encoding="utf-8")
        print(f"[lonely-emitter] wrote {out_path} from {path or mid}")
        emitted += 1
        if emitted >= args.top:
            break

    if emitted == 0:
        print("[lonely-emitter] nothing to emit (all already authored or list empty)")

if __name__ == "__main__":
    main()
