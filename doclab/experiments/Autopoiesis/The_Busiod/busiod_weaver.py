def get_model(model_name="gemini-2.5-pro"):
    """Initializes and returns the generative model."""
    return genai.GenerativeModel(model_name)

def read_module(file_path):
    """Reads the content of a module file."""
    try:
        return file_path.read_text(encoding='utf-8')
    except Exception as e:
        print(f"Error reading {file_path.name}: {e}")
        return None

def save_module(directory, filename, content):
    """Saves the essentialized module content to a file in the specified directory."""
    # -FIXED- This now correctly joins the output directory and the new filename.
    output_path = Path(directory) / filename
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        output_path.write_text(content, encoding='utf-8')
    except Exception as e:
        print(f"Error saving {filename}: {e}")

def process_module(model, module_content, module_name):
    """Generates the essentialized content using the Gemini API."""
    prompt = f"""
Your task is to act as a Systems Architect for the Pirouette Framework.
You are analyzing the provided STUB and CONTEXT not as abstract theory, but as **absolute physical laws** that govern value flow.

**PREMISE:**
Assume the Pirouette principles in this module (e.g., Information conservation, Lagrangian mechanics, Autopoiesis) are TRUE.
Assume the modern market ignores these principles, creating a massive inefficiency.
Your goal is to propose a "Universal Transactional Mechanism" to exploit this inefficiency.

**THE TRIAD OF SCALE:**
You must provide three tiers of implementation.
1. **$10 (The Probe):** A micro-experiment to validate the physics. Low risk, high falsifiability.
2. **$100 (The Loop):** A self-sustaining, automated feedback loop. (The "Passive" layer).
3. **$1000 (The Engine):** Scaling the loop using Lagrangian minimization.

**REQUIREMENTS:**
1. **Universal Archetypes:** Do not propose specific tactics (e.g., "yard sale"). Propose systemic structures (e.g., "Decentralized Inventory Liquidation").
2. **The Passive Bonus:** Prioritize mechanisms where Value is generated by structure ($K_i$) rather than constant labor ($\Gamma$).
3. **Falsifiability:** Define clear failure states for the Probe.

**OUTPUT FORMAT:**
You MUST generate a single markdown file with this exact structure:

---
id: [short-id]_BIZ
title: {module_name} - Transactional Triad
type: business_proposal
passive_score: [1-10] # 10 = Money while sleeping, 1 = Full job
complexity_score: [1-10] # 10 = Manhattan Project, 1 = Weekend project
scalability_score: [1-10] # 10 = Global/Digital, 1 = Local only
sector: [Arbitrage / Aggregation / Filtration / Generation / Infrastructure]
probe_cost_est: [Amount in $]
probe_time_est: [Hours to Setup]
requires_human_labor: [Low/Medium/High]
---

## The Mechanism (Physics of the Deal)
* **Universal Archetype:** [Name of the Concept]
* **The Inefficiency:** [What market physics are broken?]
* **The Pivot:** [How does this module exploit that gap?]

## Tier 1: The Probe ($10)
* **Concept:** [The Micro-Experiment]
* **Execution:** [What do we do?]
* **The Test:** [If X doesn't happen, we stop.]

## Tier 2: The Loop ($100)
* **Concept:** [The Self-Sustaining System]
* **Automation:** [How does it run without us?]
* **Value Capture:** [Where does the money come from?]

## Tier 3: The Engine ($1000)
* **Concept:** [The Scaled System]
* **The Moat:** [Why standard business cannot compete]

## Implementation Notes
* **Tools:** [Python libraries, APIs, or Physical tools needed]
* **Risk:** [Primary vector of failure]

SOURCE DOCUMENT: {module_name}
---
{module_content}
---
TASK: Distill the source content into its essential ## Law, ## Philosophy, and ## Art components.
"""
    response = model.generate_content(prompt)

    # -IMPROVED- This block safely extracts text and handles API blocks gracefully.
    try:
        # The safe way to get text from the response
        return ''.join(part.text for part in response.parts)
    except (ValueError, IndexError):
        # This runs if the response is empty (e.g., blocked by a safety filter)
        if response.prompt_feedback and response.prompt_feedback.block_reason:
            reason = response.prompt_feedback.block_reason.name
            print(f"  -> SKIPPING: Prompt blocked due to: {reason}")
        else:
            print("  -> SKIPPING: Received an empty response from the API.")
        return None



def main():
    p = argparse.ArgumentParser(description="Make Pirouette Inspired Business Ideas.")
    p.add_argument("modules_dir", default="C:/Users/keatw/OneDrive/Documents/Doclab/Big_Datasets/target/Pirouette_Volume_7/doclab/experiments/Autopoiesis/essentialization/essentialized", help="Path to directory with *.md modules")
    p.add_argument("--out", default="./ideas", help="Output directory for essentialized modules")
    p.add_argument("--limit", type=int, default=0, help="Limit the number of files to process")
    args = p.parse_args()

    # Ensure GOOGLE_API_KEY is set
    if not os.getenv('GOOGLE_API_KEY'):
        print("Error: GOOGLE_API_KEY environment variable not set.")
        return

    genai.configure(api_key=os.environ["GOOGLE_API_KEY"])
    model = get_model()
    
    src_dir = Path(args.modules_dir)
    files = sorted([f for f in src_dir.glob("*.md") if not f.name.lower().startswith('readme')])

    if args.limit > 0:
        files = files[:args.limit]

    print(f"Found {len(files)} modules to process.")

    for file_path in files:
        module_content = read_module(file_path)
        if module_content:
            print(f"Essentializing {file_path.name}...")
            essentialized_content = process_module(model, module_content, file_path.name)
            
            if essentialized_content:
                # -FIXED- Implements the new, safe naming convention.
                new_filename = f"{file_path.stem}_essentialized.md"
                save_module(args.out, new_filename, essentialized_content)
                print(f"  -> Successfully saved: {new_filename}")

if __name__ == "__main__":
    main()